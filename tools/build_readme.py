#!/usr/bin/env python3
"""Rebuild the folder overview section of the root README.md.

Every top-level folder with a README.md contributes the text of its
"## Overview" section. The collected overviews are written between the
BEGIN/END markers in the root README.md.

Usage:
    python3 tools/build_readme.py           # rewrite README.md
    python3 tools/build_readme.py --check   # exit 1 if README.md is outdated
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
BEGIN = "<!-- BEGIN: folder-overviews (generated by tools/build_readme.py, do not edit) -->"
END = "<!-- END: folder-overviews -->"
EXCLUDED = {"docs", "tools"}


def extract_overview(readme: Path) -> str | None:
    """Return the body of the '## Overview' section, or None if missing."""
    text = readme.read_text(encoding="utf-8")
    match = re.search(r"^## Overview\s*\n(.*?)(?=^## |\Z)", text, re.S | re.M)
    if not match:
        return None
    return match.group(1).strip() or None


def build_section() -> str:
    parts = []
    for folder in sorted(p for p in ROOT.iterdir() if p.is_dir()):
        if folder.name.startswith(".") or folder.name in EXCLUDED:
            continue
        folder_readme = folder / "README.md"
        if not folder_readme.is_file():
            print(f"warning: {folder.name}/ has no README.md, skipped", file=sys.stderr)
            continue
        overview = extract_overview(folder_readme)
        if overview is None:
            print(f"warning: {folder.name}/README.md has no '## Overview', skipped", file=sys.stderr)
            continue
        parts.append(f"### [{folder.name}]({folder.name}/)\n\n{overview}")
    return "\n\n".join(parts)


def render(current: str) -> str:
    start, end = current.find(BEGIN), current.find(END)
    if start == -1 or end == -1 or end < start:
        sys.exit(f"error: markers not found in {README.name}")
    return current[: start + len(BEGIN)] + "\n\n" + build_section() + "\n\n" + current[end:]


def main() -> int:
    current = README.read_text(encoding="utf-8")
    updated = render(current)
    if "--check" in sys.argv[1:]:
        if updated != current:
            print("README.md is outdated, run: python3 tools/build_readme.py", file=sys.stderr)
            return 1
        return 0
    if updated != current:
        README.write_text(updated, encoding="utf-8")
        print("README.md updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
